import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

// Folders that never hold the project's own interface source.
const SKIP = new Set([
  'node_modules', '.git', 'dist', 'build', 'out', 'coverage', 'vendor', 'public',
  '.next', '.nuxt', '.svelte-kit', '.astro', '.turbo', '.wrangler', '.vercel',
  'locales', 'locale', 'i18n', '__tests__', 'e2e',
]);
const UI = new Set(['.tsx', '.jsx', '.vue', '.svelte', '.astro']);
const STYLE = new Set(['.css', '.scss']);
const SINGLE_COMPONENT = new Set(['.vue', '.svelte', '.astro']);

export const indexDir = path.join('.atlas', 'scan');

/** The git blob hash, so a note's hash can be checked with `git hash-object`. */
export function blobHash(content) {
  return createHash('sha1').update(`blob ${content.length}\0`).update(content).digest('hex');
}

function walk(root) {
  const files = [];
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (SKIP.has(entry.name) || (entry.name.startsWith('.') && entry.name !== '.atlas')) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(full);
      else if (entry.isFile()) files.push(full);
    }
  };
  visit(root);
  return files;
}

const isRoute = (rel) => /(^|\/)(pages|routes|app)\//.test(rel) && !/(^|\/)components?\//.test(rel);
const isTest = (rel) => /\.(test|spec|stories)\.[^.]+$/.test(rel);

function componentNames(text, ext, file) {
  if (SINGLE_COMPONENT.has(ext)) return [path.basename(file, ext)];
  const names = [...text.matchAll(/export\s+(?:default\s+)?(?:const|function|class)\s+([A-Z]\w*)/g)].map((m) => m[1]);
  for (const m of text.matchAll(/export\s*\{([^}]+)\}/g)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop();
      if (/^[A-Z]/.test(name)) names.push(name);
    }
  }
  return [...new Set(names)];
}

function propNames(text) {
  const block = text.match(/(?:interface|type)\s+\w*Props\w*\s*(?:=|extends[^{]*)?\s*\{([\s\S]*?)\n\}/);
  return block ? [...block[1].matchAll(/^\s*(\w+)\??\s*:/gm)].map((m) => m[1]) : [];
}

// Reads a cva-style `variants: { group: { value: … } }` block by brace depth.
function variantNames(text) {
  const start = text.search(/\bvariants\s*:\s*\{/);
  if (start === -1) return [];
  const groups = [];
  let depth = 0;
  let token = '';
  for (let i = text.indexOf('{', start); i < text.length; i++) {
    const ch = text[i];
    if (ch === '{') {
      depth++;
      token = '';
    } else if (ch === '}') {
      depth--;
      token = '';
      if (depth === 0) break;
    } else if (ch === ':') {
      const key = token.trim().replace(/^['"]|['"]$/g, '');
      if (/^[\w-]+$/.test(key)) {
        if (depth === 1) groups.push({ name: key, values: [] });
        else if (depth === 2 && groups.length) groups.at(-1).values.push(key);
      }
      token = '';
    } else if (ch === ',' || ch === '\n') {
      token = '';
    } else {
      token += ch;
    }
  }
  return groups.map((g) => `${g.name}(${g.values.join('|')})`);
}

/** Build the structural index for a project. Returns the markdown and the fingerprint lines. */
export function buildIndex(root) {
  const rel = (file) => path.relative(root, file).split(path.sep).join('/');
  const components = [];
  const routes = [];
  const tokens = [];
  const handoffs = [];
  const fingerprint = [];

  for (const file of walk(root)) {
    const r = rel(file);
    const ext = path.extname(file);
    if (r.startsWith('.atlas/handoff/')) handoffs.push(r);
    if (r.startsWith('.atlas/') || isTest(r)) continue;
    const isTokens = STYLE.has(ext) || /tailwind\.config\.(c?js|mjs|ts)$/.test(r);
    if (!isTokens && !UI.has(ext)) continue;

    const content = fs.readFileSync(file);
    const text = content.toString('utf8');
    if (isTokens) {
      const names = [...new Set([...text.matchAll(/^\s*(--[\w-]+)\s*:/gm)].map((m) => m[1]))];
      if (!names.length && STYLE.has(ext)) continue;
      tokens.push({ r, names });
    } else if (isRoute(r)) {
      routes.push(r);
    } else {
      const names = componentNames(text, ext, file);
      if (!names.length) continue;
      components.push({ r, names, props: propNames(text), variants: variantNames(text) });
    }
    fingerprint.push(`${r} ${blobHash(content).slice(0, 8)}`);
  }

  const lines = [
    '# Structural index',
    '',
    'Generated by `npx ux-atlas scan`. Search this file. Do not read it whole. Regenerate it; do not edit it.',
    '',
    `generated: ${new Date().toISOString()}`,
    `DESIGN.md: ${fs.existsSync(path.join(root, 'DESIGN.md')) ? 'present' : 'absent'}`,
    `counts: ${components.length} component files, ${routes.length} route files, ${tokens.length} token files`,
    '',
    '## Tokens',
    ...tokens.map(({ r, names }) => `- ${r}: ${names.length ? names.join(' ') : 'theme config, no custom properties'}`),
    '',
    '## Components',
  ];
  let folder = '';
  for (const c of components.sort((a, b) => a.r.localeCompare(b.r))) {
    const dir = path.posix.dirname(c.r);
    if (dir !== folder) lines.push(`### ${dir}`);
    folder = dir;
    const parts = [c.names.join(', ')];
    if (c.props.length) parts.push(`props: ${c.props.join(' ')}`);
    if (c.variants.length) parts.push(`variants: ${c.variants.join(' ')}`);
    lines.push(`- ${path.posix.basename(c.r)} — ${parts.join(' — ')}`);
  }
  lines.push('', '## Routes', ...routes.sort().map((r) => `- ${r}`));
  lines.push('', '## Handoffs', ...(handoffs.length ? handoffs.sort().map((h) => `- ${h}`) : ['- none']), '');

  return { markdown: lines.join('\n'), fingerprint: fingerprint.sort() };
}

/** Write `.atlas/scan/index.md` and `.atlas/scan/index.fingerprint` under the project root. */
export function writeIndex(root) {
  const { markdown, fingerprint } = buildIndex(root);
  const directory = path.join(root, indexDir);
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, 'index.md'), markdown);
  fs.writeFileSync(path.join(directory, 'index.fingerprint'), `${fingerprint.join('\n')}\n`);
  return { files: fingerprint.length, directory };
}
